# --- Test 8: explicit language request is honored -----------------------------------------


def test_explicit_language_request_selects_the_requested_translation():
    language = detect("Please answer in Finnish.")
    assert language.name == "Finnish" and language.explicit
    localized = localize_fallback_message(
        "Thanks for your question, we've taken note of it and will follow up once we have an answer.", language
    )
    assert localized.startswith("Kiitos kysymyksestäsi")


# --- Test 9: ambiguous language keeps the existing safe default ---------------------------


async def test_ambiguous_language_keeps_the_english_default(db, embedder, llm):
    language = detect(AMBIGUOUS_Q)
    assert language.name is None and language.script == "latin"  # Dutch is not implicitly named — by design

    result = await _limitation_reply(db, AMBIGUOUS_Q)
    assert result.is_fallback and "doesn't establish an answer" in result.answer  # unchanged, safe default


def test_customized_message_is_never_auto_translated():
    language = ResponseLanguage(name="Finnish", script="latin", explicit=True)
    custom = "Please contact support@example.com for help with this."
    assert localize_fallback_message(custom, language) == custom  # not the shipped default -> untouched


# --- Test 10: technical identifiers are preserved in every language ----------------------


async def test_technical_identifiers_survive_localization(db, embedder, llm):
    for question in (QUESTIONS["Finnish"], QUESTIONS["German"], ARABIC_Q):
        result = await _limitation_reply(db, question)
        assert "CUB3-45NS" in result.answer  # model code copied verbatim, never translated


def test_limitation_message_never_translates_technical_identifiers():
    language = ResponseLanguage(name="French", script="latin", explicit=True)
    message = limitation_message("SW3-45NS", ["NB", "STE"], language)
    assert "SW3-45NS" in message and "NB" in message and "STE" in message
    assert "ne permet pas de répondre" in message


# --- off-topic localization (unit-level: see test_response_language.py for the -----------
# --- LLM-generated off-topic reply path, which this phase does not change) ---------------


def test_off_topic_message_is_localized_for_a_supported_language():
    language = ResponseLanguage(name="German", script="latin", explicit=True)
    localized = localize_off_topic_message(
        "I'm here to help with product and technical support questions — what can I help you with?", language
    )
    assert "womit kann ich helfen" in localized


def test_off_topic_message_falls_back_to_default_for_unsupported_language():
    language = ResponseLanguage(name=None, script="latin", explicit=False)
    message = "I'm here to help with product and technical support questions — what can I help you with?"
    assert localize_off_topic_message(message, language) == message
